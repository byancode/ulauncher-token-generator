"""Cryptographically secure value generators.

This module has no Ulauncher imports on purpose, so it can be unit tested
outside of the Ulauncher runtime.

Every random value produced here comes from :mod:`secrets` (os.urandom), never
from the :mod:`random` Mersenne Twister.
"""

import base64
import hashlib
import math
import secrets
import string
import threading
import time
import uuid

DIGITS = string.digits
LETTERS = string.ascii_letters
ALPHANUMERIC = LETTERS + DIGITS
URL_SAFE = ALPHANUMERIC + "-_"
HEX_CHARS = "0123456789abcdef"
SYMBOLS = "!@#$%^&*()-_=+[]{};:,.?/"
# Characters that are easy to mistake for one another in most fonts.
AMBIGUOUS_CHARS = "Il1O0o|`'\""
CROCKFORD32 = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
HASH_ALGORITHMS = ("sha256", "sha1", "md5", "sha512")

_MAX_ULID_RANDOM = (1 << 80) - 1
_MAX_UUID7_COUNTER = 0x1000 - 1

_ulid_lock = threading.Lock()
_ulid_last_ms = -1
_ulid_last_random = 0

_uuid7_lock = threading.Lock()
_uuid7_last_ms = -1
_uuid7_counter = 0


def _check_length(length):
    if not isinstance(length, int) or isinstance(length, bool):
        raise TypeError("length must be an int")
    if length < 1:
        raise ValueError("length must be at least 1")


def _strip_chars(alphabet, chars):
    return "".join(c for c in alphabet if c not in chars)


def random_string(length, alphabet=URL_SAFE):
    """Return ``length`` characters drawn uniformly from ``alphabet``."""
    _check_length(length)
    if not alphabet:
        raise ValueError("alphabet cannot be empty")
    return "".join(secrets.choice(alphabet) for _ in range(length))


def url_safe_token(length=32, exclude_ambiguous=False):
    """Random token that is safe inside URLs, shells and JSON strings."""
    alphabet = _strip_chars(URL_SAFE, AMBIGUOUS_CHARS) if exclude_ambiguous else URL_SAFE
    return random_string(length, alphabet)


def hex_token(length=32):
    """Lowercase hexadecimal token with exactly ``length`` characters."""
    _check_length(length)
    return secrets.token_hex((length + 1) // 2)[:length]


def numeric_code(length=6):
    """Numeric code (PIN/OTP style) that may start with zeros."""
    return random_string(length, DIGITS)


def password(length=20, symbols=True, exclude_ambiguous=False):
    """Password guaranteed to contain a lower, upper and digit character.

    When ``symbols`` is true at least one symbol is included as well, as long
    as ``length`` leaves room for every required character class.
    """
    _check_length(length)

    classes = [string.ascii_lowercase, string.ascii_uppercase, DIGITS]
    if symbols:
        classes.append(SYMBOLS)
    if exclude_ambiguous:
        classes = [_strip_chars(c, AMBIGUOUS_CHARS) for c in classes]
    classes = [c for c in classes if c]

    alphabet = "".join(classes)
    chars = [secrets.choice(c) for c in classes] if length >= len(classes) else []
    chars.extend(secrets.choice(alphabet) for _ in range(length - len(chars)))
    secrets.SystemRandom().shuffle(chars)
    return "".join(chars)


def base64_token(num_bytes=24):
    """URL-safe Base64 string without ``=`` padding."""
    _check_length(num_bytes)
    return base64.urlsafe_b64encode(secrets.token_bytes(num_bytes)).decode("ascii").rstrip("=")


def api_key(length=32, prefix="sk_"):
    """Prefixed API-key style secret, e.g. ``sk_9f3c...``."""
    return "%s%s" % (prefix, url_safe_token(length))


def uuid4_str():
    """Random (version 4) UUID."""
    return str(uuid.uuid4())


def uuid7_str():
    """Time-ordered UUID version 7 (RFC 9562).

    Values generated by this process are monotonically increasing, because a
    dedicated 12-bit counter replaces part of the random payload within the
    same millisecond.
    """
    global _uuid7_last_ms, _uuid7_counter

    with _uuid7_lock:
        now_ms = int(time.time() * 1000)
        if now_ms > _uuid7_last_ms:
            _uuid7_counter = secrets.randbelow(_MAX_UUID7_COUNTER + 1)
        elif _uuid7_counter < _MAX_UUID7_COUNTER:
            # Same millisecond (or the clock moved backwards): keep ordering.
            now_ms = max(now_ms, _uuid7_last_ms)
            _uuid7_counter += 1
        else:
            while now_ms <= _uuid7_last_ms:
                time.sleep(0.001)
                now_ms = int(time.time() * 1000)
            _uuid7_counter = secrets.randbelow(_MAX_UUID7_COUNTER + 1)
        _uuid7_last_ms = now_ms

        timestamp = now_ms & ((1 << 48) - 1)
        value = (
            (timestamp << 80)
            | (0x7 << 76)
            | (_uuid7_counter << 64)
            | (0b10 << 62)
            | secrets.randbits(62)
        )

    return str(uuid.UUID(int=value))


def ulid_str():
    """Monotonically increasing 26-character ULID (Crockford base32)."""
    global _ulid_last_ms, _ulid_last_random

    with _ulid_lock:
        now_ms = int(time.time() * 1000)
        if now_ms > _ulid_last_ms:
            _ulid_last_ms = now_ms
            _ulid_last_random = secrets.randbits(80)
        elif _ulid_last_random < _MAX_ULID_RANDOM:
            _ulid_last_random += 1
        else:
            while now_ms <= _ulid_last_ms:
                time.sleep(0.001)
                now_ms = int(time.time() * 1000)
            _ulid_last_ms = now_ms
            _ulid_last_random = secrets.randbits(80)

        value = (_ulid_last_ms << 80) | _ulid_last_random

    return _encode_crockford(value, 26)


def _encode_crockford(value, length):
    chars = []
    for _ in range(length):
        chars.append(CROCKFORD32[value & 0x1F])
        value >>= 5
    return "".join(reversed(chars))


def hash_text(text, algorithm="sha256"):
    """Hex digest of ``text`` for one of :data:`HASH_ALGORITHMS`."""
    if algorithm not in HASH_ALGORITHMS:
        raise ValueError("unsupported algorithm: %s" % algorithm)
    return hashlib.new(algorithm, text.encode("utf-8")).hexdigest()


def entropy_bits(alphabet_size, length):
    """Approximate entropy of a value, in bits."""
    if alphabet_size < 2 or length < 1:
        return 0.0
    return round(math.log2(alphabet_size) * length, 1)
